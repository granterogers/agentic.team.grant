/*
  0516 — the task "that" means (#259).

  A conversation could create a personal task and could never change one.
  *"Actually make that Monday"* did nothing at all: `personalTaskChange`
  (0516's companion in `src/agents/mine.ts`) now reads the change, and this is
  the half that answers WHICH task.

  ## Most recent, and only just

  The referent in "make that Monday" is the task the office just made. So the
  answer is the most recently CREATED open personal task, inside a short
  window, and nothing cleverer:

  - **Not a title match.** "Move the venue one to Friday" would be one fuzzy
    match away from editing a row Grant did not mean, and the entire value of a
    to-do list is that it says what you put in it. The handler NAMES what it
    changed, which is the honest alternative to guessing well.
  - **Bounded to thirty minutes.** Past that, "that" is not a referent to
    anything in the conversation — it is a word in a sentence about something
    else, and the failure of resolving it would be silent.
  - **Open only.** A finished task is not what "that" means, and reopening one
    by moving its date is not what anybody asked for.

  Returns null rather than a guess when there is nothing in the window, so the
  caller can say it does not know which task — which is the answer #259's
  invariant about never claiming a change demands.

  ## And it cannot be ordered by `created_at` alone

  The drive block below caught this before the function shipped: `created_at`
  defaults to `now()`, which is the TRANSACTION timestamp, so two tasks written
  in one statement carry the same value to the microsecond and "the newest"
  becomes a coin flip. That is not hypothetical here — `office.extract_tasks`
  pulls several tasks out of one document in a single statement, and after that
  "make that Monday" would move whichever row Postgres felt like.

  CLAUDE.md records the identical defect deciding which project a chat was
  pointed at, and its fix: *"a monotonic identity column is the tiebreaker —
  assigned by the sequence at INSERT, so it reflects write order where the
  clock cannot."* `tasks.seq` is that column, and the rule from that entry
  applies unchanged: before ordering by a uuid, ask what it is standing in for.
*/

alter table public.tasks
  add column if not exists seq bigint generated by default as identity;

comment on column public.tasks.seq is
  'Write order, for the times the clock cannot give it. created_at is the '
  'transaction timestamp, so tasks written in one statement share it exactly '
  '(0516).';

create index if not exists tasks_mine_recent on public.tasks (seq desc)
  where assigned_to_human and state not in ('done', 'cancelled');

create or replace function app.my_task_recent(p_within interval default interval '30 minutes')
returns jsonb
language sql
stable
security definer
set search_path = ''
as $fn$
  select case when t.task_id is null then null else jsonb_build_object(
           'id', t.task_id,
           'title', t.title,
           'due_on', t.due_on,
           'priority', t.priority,
           'created_at', t.created_at) end
    from (
      select *
        from public.tasks
       where assigned_to_human
         and state not in ('done', 'cancelled')
         and not coalesce(is_fixture, false)
         and created_at >= app.now_utc() - p_within
       /*
         `seq`, then the clock. The sequence is assigned at INSERT so it is
         correct even inside one statement; `created_at` is kept as the second
         key only so a row that predates the column still sorts sensibly.
       */
       order by seq desc nulls last, created_at desc
       limit 1
    ) t
$fn$;

comment on function app.my_task_recent(interval) is
  'The task a follow-up means by "that" (#259): the most recently created open '
  'personal task inside a short window, or null. Deliberately not a title '
  'match — a fuzzy match is one bad guess away from editing the wrong row.';

grant execute on function app.my_task_recent(interval) to ai_team_app, service_role;

do $drive$
declare
  v_a uuid;
  v_b uuid;
  v_got jsonb;
begin
  /*
    Both in ONE statement's worth of time, deliberately.

    `pg_sleep` between them proves nothing: `now()` is the transaction
    timestamp and does not move. That is the whole point — this is the case
    `created_at` cannot order, and the first version of this function failed
    here, which is the drive block doing its job.
  */
  v_a := (app.my_task_add('Referent probe 0516 older') ->> 'id')::uuid;
  v_b := (app.my_task_add('Referent probe 0516 newer') ->> 'id')::uuid;
  if (select created_at from public.tasks where task_id = v_a)
     <> (select created_at from public.tasks where task_id = v_b) then
    raise exception '0516: the control is not testing what it claims — the two '
                    'probes have different created_at, so the clock could have '
                    'ordered them and the sequence was never needed';
  end if;

  v_got := app.my_task_recent();
  if (v_got ->> 'id')::uuid <> v_b then
    raise exception '0516: "that" resolved to % rather than the newest task', v_got ->> 'title';
  end if;

  -- CONTROL: finishing it moves the referent back to the one before.
  perform app.hq_task_state(v_b::text, 'done', 'probe');
  v_got := app.my_task_recent();
  if (v_got ->> 'id')::uuid <> v_a then
    raise exception 'CONTROL FAILED: a finished task is still what "that" means';
  end if;

  /*
    CONTROL: a task from two hours ago is not what "that" means.

    Written with an explicit `created_at` rather than by shrinking the window
    to zero — the first version did that and failed, correctly: inside one
    transaction every row's `created_at` IS now(), so `created_at >= now() - 0`
    is true and the control was asking a question the transaction cannot
    express. Back-dating the row asks the real one.
  */
  delete from public.tasks where title like 'Referent probe 0516%';
  insert into public.tasks (title, assigned_to_human, added_by, state, created_at)
  values ('Referent probe 0516 stale', true, 'migration', 'todo',
          app.now_utc() - interval '2 hours');
  if app.my_task_recent() is not null then
    raise exception 'CONTROL FAILED: a task from two hours ago answered "that" — %',
      app.my_task_recent() ->> 'title';
  end if;
  if app.my_task_recent(interval '3 hours') is null then
    raise exception 'CONTROL FAILED: and a wide enough window does not find it either, '
                    'so the window is not what excluded it';
  end if;

  -- CONTROL: the team's own work is never what "that" means.
  delete from public.tasks where title like 'Referent probe 0516%';
  insert into public.tasks (title, assigned_to_human, added_by, state)
  values ('Referent probe 0516 theirs', false, 'migration', 'todo');
  if app.my_task_recent() is not null
     and (app.my_task_recent() ->> 'title') like 'Referent probe 0516%' then
    raise exception 'CONTROL FAILED: the team''s own task answered a personal referent';
  end if;

  delete from public.tasks where title like 'Referent probe 0516%';
  raise notice '0516: the referent is the newest open personal task, and three controls hold';
end
$drive$;

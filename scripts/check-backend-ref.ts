/*
 * NOTHING SERVED TO A BROWSER MAY NAME A PARTICULAR OFFICE.
 *
 *   npm run check:backend-ref
 *   npm run check:backend-ref -- --prove-it     # sabotage, expect red, restore
 *
 * ## The defect this is the regression for
 *
 * IR-1. Six modules under `web/studio`, plus the voice page and the inline
 * block in `index.html`, each carried a Supabase project reference:
 *
 *     window.HQ_API || 'https://<a project ref>.supabase.co/functions/v1/hq-api'
 *
 * Somebody who clones this repository and deploys it got a dashboard pointing
 * at an office that is not theirs. Nothing leaked -- the gateway verifies the
 * session with Supabase and checks its own membership list -- but they were
 * refused with a 401 and no explanation, which reads as a broken product.
 *
 * `web/studio/backend.js` resolves the address from one place and returns the
 * empty string when nothing named one; `npm run config:site` writes the one
 * place, at deploy time, into a file that is not in the repository. This check
 * is what stops the fallback coming back -- and it will be tempting to bring
 * back, because a hardcoded address makes a local page work.
 *
 * ## Scope, and why `scripts/` and `src/` are deliberately not in it
 *
 * F-009: 252 files under `scripts/` and `src/` default to this project, and
 * that default must STAY. They are Grant's operational commands, and an
 * operator who has to set an environment variable before every command is an
 * operator who stops using the commands. A fresh install sets
 * `SUPABASE_PROJECT_REF` once in `npm run fresh:configure` and everything
 * follows.
 *
 * What is different about `web/` is that it is SERVED. Nobody types a command
 * to get it; it arrives in a stranger's browser.
 *
 * ## What it looks for
 *
 * A Supabase project host, in any file under `web/`, whatever it is doing
 * there. Deliberately the SHAPE rather than a list of known references -- a
 * list of known offices would go stale the day somebody pastes a different
 * one, and CLAUDE.md records four separate occasions where an enumeration was
 * asserted where a property was meant.
 */
import '../src/safety/arm.ts'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const ROOT = 'web'

/*
  A Supabase project host. `<ref>.supabase.co` is the shape every one of them
  has, and the reference is 20 lower-case letters -- but the check does not
  require that length, because a reference that is one character different is
  the same defect.
*/
const NAMES_A_PROJECT = /\b[a-z0-9-]{8,}\.supabase\.(co|in)\b/

/*
  The exemptions, each with the reason it is one. A baselined reason is a claim
  about the product and CLAUDE.md records two that were false, so each of these
  says something that can be checked by reading the file.
*/
const ALLOWED: { readonly path: string; readonly why: string }[] = [
  {
    path: 'web/studio/config.js',
    why: 'generated by npm run config:site and gitignored — it is the one place a DEPLOYMENT names its own office, and a clone does not have it',
  },
]

const walk = async (dir: string): Promise<string[]> => {
  const out: string[] = []
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, e.name).split('\\').join('/')
    if (e.isDirectory()) out.push(...(await walk(full)))
    else out.push(full)
  }
  return out
}

/** Text files only: a project reference cannot hide in a font or a photograph. */
const TEXT = /\.(js|mjs|ts|html|css|json|svg|md|txt)$/i

export type Hit = { readonly file: string; readonly line: number; readonly text: string }

export const scan = async (): Promise<Hit[]> => {
  const hits: Hit[] = []
  for (const file of await walk(ROOT)) {
    if (!TEXT.test(file)) continue
    if (ALLOWED.some((a) => a.path === file)) continue
    const body = await readFile(file, 'utf8')
    body.split('\n').forEach((text, i) => {
      if (NAMES_A_PROJECT.test(text)) hits.push({ file, line: i + 1, text: text.trim() })
    })
  }
  return hits
}

/*
  THE CONTROL.

  A check that has only ever reported zero is indistinguishable from one that
  cannot report anything, and this one's happy path is "found nothing" -- the
  exact shape CLAUDE.md names three times. So it can be asked to put the defect
  back, watch itself go red, and restore.
*/
const proveIt = async (): Promise<number> => {
  const victim = 'web/studio/office.js'
  const before = await readFile(victim, 'utf8')
  const sabotaged = before.replace(
    "import { HQ_API as API } from './backend.js'",
    "import { HQ_API } from './backend.js'\nconst API = HQ_API || 'https://someoffice.supabase.co/functions/v1/hq-api'",
  )
  if (sabotaged === before) {
    console.error('SABOTAGE DID NOT APPLY — the import line in office.js has been reworded.')
    console.error('A sabotage that did not land is not a passing control. Nothing was proved.')
    return 2
  }
  await writeFile(victim, sabotaged)
  const applied = (await readFile(victim, 'utf8')).includes('someoffice.supabase.co')
  console.log(`sabotage landed in ${victim}: ${String(applied)}`)
  const red = await scan()
  await writeFile(victim, before)
  const green = await scan()

  console.log(`with the fallback back:     ${String(red.length)} finding(s)`)
  console.log(`with it removed again:      ${String(green.length)} finding(s)`)
  if (red.length === 0) {
    console.error('THE CHECK CANNOT FAIL. A reintroduced fallback was not seen.')
    return 1
  }
  if (green.length !== 0) {
    console.error('the restore did not restore — the tree is not as it was')
    return 1
  }
  console.log('CONTROL PASSED: the check goes red on a reintroduced fallback and green again.')
  return 0
}

if (process.argv.includes('--prove-it')) {
  process.exit(await proveIt())
}

const hits = await scan()
if (hits.length === 0) {
  console.log(`check:backend-ref — clean. Nothing under ${ROOT}/ names a particular office.`)
  for (const a of ALLOWED) console.log(`  allowed: ${a.path} — ${a.why}`)
  process.exit(0)
}

console.error(`check:backend-ref — ${String(hits.length)} file line(s) name a particular office:\n`)
for (const h of hits) console.error(`  ${h.file}:${String(h.line)}  ${h.text.slice(0, 120)}`)
console.error(
  '\nA page served to a browser may not name one office. Resolve the address through' +
    '\nweb/studio/backend.js, and let npm run config:site supply it at deploy time.' +
    '\nSee IR-1 in docs/fresh-install/INTEGRATION-REQUESTS.md.',
)
process.exit(1)

/**
 * Does any database function write a carrier row without naming its office? (multi-user P3, Wave 12)
 *   npm run check:carrier-writers
 *
 * The compatibility bridge gave an insert that named no office to the only person. P3 removed it, so a function that
 * still inserts into a carrier table without `office_id` fails on NOT NULL the first time anything calls it - and an
 * operator command or a rare path can sit unused for weeks, which is how six of them survived a meter that read zero.
 * This reads every function body instead of waiting for it to run.
 *
 * A trigger that fills the office from the row's own parent is a legitimate alternative to naming it, so a table whose
 * insert is covered by a BEFORE INSERT trigger other than the removed bridge is listed with its triggers rather than failed.
 */
import '../../src/safety/require-production-unless-replica.ts'
import { openCatalogue } from '../lib/catalogue-db.ts'

/** The pure predicate, exported so the control below can drive it with a defect. */
export const insertsWithoutOffice = (source: string, tables: readonly string[]): string[] => {
  const bare = source.replace(/--[^\n]*/g, '').replace(/\/\*[\s\S]*?\*\//g, '')
  const hits: string[] = []
  for (const t of tables) {
    const re = new RegExp(`insert\\s+into\\s+(?:public\\.)?${t}\\b\\s*(\\([^)]*\\))?`, 'gi')
    for (const m of bare.matchAll(re)) {
      if (m[1] === undefined || !/office_id/i.test(m[1])) hits.push(t)
    }
  }
  return hits
}

if (import.meta.url === `file://${process.argv[1]}`) {
  // The control: a defect the predicate must see, and a correct write it must not.
  const bad = insertsWithoutOffice(
    'insert into public.signals (source, event_type) values (1, 2)',
    ['signals'],
  )
  const good = insertsWithoutOffice(
    'insert into public.signals (office_id, source) values (1, 2)',
    ['signals'],
  )
  if (bad.length !== 1 || good.length !== 0) {
    console.log(
      'FAIL the predicate cannot tell a writer that names its office from one that does not',
    )
    process.exit(1)
  }

  const db = await openCatalogue()
  const tables = (
    (
      await db.execute(`
        select c.relname as t from pg_class c join pg_namespace n on n.oid = c.relnamespace
          join pg_attribute a on a.attrelid = c.oid and a.attname = 'office_id' and not a.attisdropped
         where n.nspname = 'public' and c.relkind = 'r'`)
    ).rows as { t: string }[]
  )
    .map((r) => r.t)
    // `offices` is the office itself: its `office_id` is its own key, generated by the insert, not an owner it names.
    .filter((t) => t !== 'offices')
  const fns = (
    await db.execute(`
      select p.oid::regprocedure::text as sig, p.prosrc as src
        from pg_proc p join pg_namespace n on n.oid = p.pronamespace
       where n.nspname in ('app', 'public') and p.prokind = 'f'`)
  ).rows as { sig: string; src: string }[]
  if (tables.length < 50 || fns.length < 500) {
    console.log(
      `FAIL looked at ${String(tables.length)} carrier(s) and ${String(fns.length)} function(s): too few to mean anything`,
    )
    process.exit(1)
  }
  const found = fns.flatMap((f) =>
    insertsWithoutOffice(f.src, tables).map((t) => `${f.sig} -> ${t}`),
  )
  console.log(
    `read ${String(fns.length)} function(s) against ${String(tables.length)} carrier table(s)`,
  )
  if (found.length > 0) {
    console.log(
      `FAIL ${String(found.length)} writer(s) insert a carrier row without naming its office:`,
    )
    for (const f of found) console.log(`  ${f}`)
    process.exit(1)
  }
  console.log('ok   every function that inserts into a carrier names the office')
}

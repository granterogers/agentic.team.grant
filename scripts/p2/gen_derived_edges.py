#!/usr/bin/env python3
"""Generate migration 0660 (derived ownership edges) from the ownership manifest and the live catalogue.

Usage: python3 scripts/p2/gen_derived_edges.py > migrations/0660_derived_tables_cannot_cross_offices.sql

A derived table carries no office column; its owner is the owner of the row its NOT NULL path reaches. A composite
key cannot say that, so each derived table that has a second owned edge (and each carrier whose second edge reaches a
derived table) gets a trigger that computes the owner both ways and refuses a disagreement. The same trigger refuses to
let a derived row's path move to another office.

The manifest is the only source of which tables exist and how they are classed; the catalogue is only asked for the
referenced columns of a named foreign key."""
import json, subprocess, sys

PSQL = ['psql', '-h', '/tmp/pgs', '-p', '55432', '-U', 'postgres', '-d', 'post', '-qtA', '-F', '|']
m = json.load(open('docs/multi-user/ownership-manifest.json'))['tables']

def q(sql):
    return [r.split('|') for r in subprocess.check_output(PSQL + ['-c', sql], text=True).strip().split('\n') if r]

fk = {}   # (child, constraint) -> (child cols, parent, parent cols)
for child, con, ccols, parent, pcols in q("""
  select c.conrelid::regclass::text, c.conname,
         (select string_agg(a.attname, ',' order by k.ord) from unnest(c.conkey) with ordinality k(n, ord) join pg_attribute a on a.attrelid = c.conrelid and a.attnum = k.n),
         c.confrelid::regclass::text,
         (select string_agg(a.attname, ',' order by k.ord) from unnest(c.confkey) with ordinality k(n, ord) join pg_attribute a on a.attrelid = c.confrelid and a.attnum = k.n)
    from pg_constraint c where c.contype = 'f' and c.connamespace = 'public'::regnamespace"""):
    fk[(child.replace('public.', ''), con)] = (ccols.split(','), parent.replace('public.', ''), pcols.split(','))

def expr(table, alias, depth=0):
    """SQL for the office of the row `alias` of `table`."""
    cls = m[table]['class']
    if cls == 'OFFICE_CARRIER':
        return f'{alias}.office_id'
    if cls != 'OFFICE_DERIVED':
        raise SystemExit(f'{table} is {cls}: it has no office to resolve')
    p = m[table]['path'][0]
    ccols, parent, pcols = fk[(table, p['constraint'])]
    a = f'p{depth}'
    cond = ' and '.join(f'{a}.{pc} = {alias}.{cc}' for cc, pc in zip(ccols, pcols))
    return f'(select {expr(parent, a, depth + 1)} from public.{parent} {a} where {cond})'

def path_cols(table):
    return fk[(table, m[table]['path'][0]['constraint'])][0]

targets = []   # (table, class, edges)
for t, v in m.items():
    if v['class'] == 'OFFICE_DERIVED':
        edges = [c for c in v.get('cross', [])]
        targets.append((t, edges))
    elif v['class'] == 'OFFICE_CARRIER':
        edges = [c for c in v.get('cross', []) if m[c['parent']]['class'] == 'OFFICE_DERIVED']
        if edges:
            targets.append((t, edges))

out = []
w = out.append
w("""-- 0660 - derived tables cannot cross offices (multi-user P2).  GENERATED by scripts/p2/gen_derived_edges.py.
--
-- A derived table has no office column: its owner is whoever owns the row its NOT NULL path reaches. So a composite
-- key cannot say "my second parent is in my office". These triggers compute the owner both ways and refuse a
-- disagreement, and refuse to let a derived row's path move it to another office. Service-role and worker writers pass
-- through them like everyone else: a trigger is part of the table, not of the caller.
--
-- The path of every derived table is asserted NOT NULL here, so the owner always exists.
""")
w("do $m$\nbegin")
for t, v in m.items():
    if v['class'] == 'OFFICE_DERIVED':
        for c in path_cols(t):
            w(f"  if (select is_nullable from information_schema.columns where table_schema = 'public' and table_name = '{t}' and column_name = '{c}') <> 'NO' then")
            w(f"    raise exception '0660: derived table {t} has a nullable path column {c}: its owner would not always exist';")
            w("  end if;")
w("end $m$;\n")

for t, edges in targets:
    own_new = expr(t, 'new')
    own_old = expr(t, 'old')
    fn = f'app.p2_edge_{t}'
    cols = set()
    if m[t]['class'] == 'OFFICE_DERIVED':
        cols |= set(path_cols(t))
    body = []
    for e in edges:
        ccols, parent, pcols = fk[(t, e['constraint'])]
        cols |= set(ccols)
        nn = ' and '.join(f'new.{c} is not null' for c in ccols)
        cond = ' and '.join(f'x.{pc} = new.{cc}' for cc, pc in zip(ccols, pcols))
        body.append(f"""  if {nn} then
    v_other := (select {expr(parent, 'x', 1)} from public.{parent} x where {cond});
    if v_other is distinct from v_own then
      raise exception '{t}.{",".join(ccols)} names a row of another office' using errcode = '23514';
    end if;
  end if;""")
    move = ''
    if m[t]['class'] == 'OFFICE_DERIVED':
        move = f"""  if tg_op = 'UPDATE' then
    v_old := {own_old};
    if v_old is distinct from v_own then
      raise exception '{t}: a row cannot move to another office' using errcode = '23514';
    end if;
  end if;
"""
    # Inserting needs the comparison only when there is a second edge to compare; moving is checked on every update
    events = 'insert or update of' if edges else 'update of'
    if not edges:
        own_decl = ''
    w(f"""create function {fn}()
returns trigger
language plpgsql
set search_path to ''
as $f$
declare
  v_own uuid;
  v_old uuid;
  v_other uuid;
begin
  v_own := {own_new};
{move}{chr(10).join(body)}
  return new;
end
$f$;
revoke all on function {fn}() from public, anon, authenticated, service_role;
create trigger a2_office_edges before {events} {", ".join(sorted(cols))} on public.{t}
  for each row execute function {fn}();
""")
w("""-- ROLLBACK (not part of the migration): drop trigger a2_office_edges on each table named above and drop the app.p2_edge_* functions.""")
print('\n'.join(out))

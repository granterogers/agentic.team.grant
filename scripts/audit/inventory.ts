/**
 * The complete credential and account inventory, checked live.
 *
 *   npm run inventory
 *
 * ## Why this is a script and not a document
 *
 * There has been a credential document since 2026-09-03, whose stated purpose
 * was "stop asking Grant for credentials one at a time". It did not work, and
 * the reason is worth being precise about: **a document is a snapshot, and this
 * information changes.** Keys are added, keys die, accounts are banned. A
 * document that is right on Tuesday is quietly wrong by Friday, and nobody can
 * tell which day it is by reading it.
 *
 * So the inventory is generated by asking each service whether the credential
 * still works. It cannot drift, because it is not stored.
 *
 * ## What it records that the document never did
 *
 * **Which account each thing hangs off.** The old list tracked "what key do I
 * need". It never tracked "what does this key depend on" — and on 2026-09-04
 * Google disabled one account that four vendors had been signed up with, which
 * turned a single event into a week of discoveries. Ownership is now a column.
 *
 * Prints nothing secret: names, status, owner, and what to do.
 */

import { ManagementApiExecutor } from '../../src/db/executor.ts'

const supabaseToken = process.env.SUPABASE_ACCESS_TOKEN ?? ''
const db = new ManagementApiExecutor(
  process.env.SUPABASE_PROJECT_REF ?? 'baujwlzcziasnfhhkchg',
  supabaseToken,
)

type State =
  | 'ok'
  | 'dead'
  | 'missing'
  | 'unknown'
  /**
   * Deliberately not being pursued, and not a gap.
   *
   * Added because two rows sat under "needs Grant" after Grant had answered
   * them — Backblaze was confirmed safe and TTS was parked — and a list of
   * outstanding items that includes settled ones is a list nobody finishes
   * reading.
   */
  | 'parked'
interface Row {
  service: string
  what: string
  state: State
  owner: string
  detail: string
  action: string
}
const rows: Row[] = []

const check = async (
  service: string,
  what: string,
  owner: string,
  action: string,
  probe: () => Promise<{ ok: boolean; detail: string }>,
): Promise<void> => {
  try {
    const { ok, detail } = await probe()
    rows.push({ service, what, state: ok ? 'ok' : 'dead', owner, detail, action })
  } catch (error) {
    rows.push({
      service,
      what,
      state: 'unknown',
      owner,
      detail: (error as Error).message.slice(0, 60),
      action,
    })
  }
}


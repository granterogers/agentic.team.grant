/*
 * WHICH OFFICE THE DASHBOARD BELONGS TO, written where the browser can read it.
 *
 *   npm run config:site                 # this project, from the environment
 *   npm run config:site -- --print      # say what it would write, write nothing
 *
 * ## Why this exists
 *
 * Six modules under `web/studio` each carried
 *
 *     window.HQ_API || 'https://<a project ref>.supabase.co/functions/v1/hq-api'
 *
 * which is one person's office written into generic product code. Somebody who
 * clones this repository and deploys it gets a dashboard pointing at an office
 * that is not theirs, refused with a 401 and no explanation. IR-1.
 *
 * `web/studio/backend.js` resolves the address from one place and returns the
 * empty string when nothing has named one. This is what names one: a generated
 * `web/studio/config.js`, which is NOT in the repository, so a clone has no
 * default to be wrong about.
 *
 * ## Why the generated file is not a secret
 *
 * The gateway's address is public -- the browser calls it. The authorization
 * boundary is entirely server-side: a Supabase Auth session, verified with
 * Supabase, and the office's own membership list. Nothing written here is a
 * credential and `npm run check:secrets` is unaffected.
 *
 * ## The default, and F-009
 *
 * `SUPABASE_PROJECT_REF` defaults to this office's, exactly as the other 250-odd
 * places in `scripts/` do, and F-009 records why that default must stay: these
 * are Grant's operational scripts and an operator who has to set an environment
 * variable before every command is an operator who stops using the commands. A
 * fresh install sets it once, in `npm run fresh:configure`, and everything
 * downstream -- including this -- follows.
 */
import { writeFile } from 'node:fs/promises'

const ref = process.env.SUPABASE_PROJECT_REF ?? 'baujwlzcziasnfhhkchg'
const slug = process.env.HQ_API_SLUG ?? 'hq-api'
const base = process.env.SUPABASE_FUNCTIONS_URL ?? `https://${ref}.supabase.co/functions/v1`

export const siteConfig = (): string =>
  [
    '/*',
    '  GENERATED by `npm run config:site`. Not in the repository, deliberately:',
    "  a committed default is one office's address shipped to everybody who",
    '  clones this, which is the defect `backend.js` exists to close.',
    '',
    '  Nothing here is a credential. The gateway address is public -- the browser',
    '  calls it -- and every authorization decision is made server-side.',
    '*/',
    `window.HQ_API = '${base}/${slug}'`,
    '',
  ].join('\n')

const out = 'web/studio/config.js'
const body = siteConfig()

if (process.argv.includes('--print')) {
  console.log(body)
} else {
  await writeFile(out, body)
  console.log(`wrote ${out} -> ${base}/${slug}`)
}

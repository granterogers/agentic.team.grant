/**
 * Emit CREATE ROLE statements for every role the dump's grants can reference.
 *
 *   npm run backup:roles > roles.sql
 *
 * A `pg_dump` of schemas carries GRANT statements naming roles, and `psql`
 * aborts on the first one that does not exist in the target. A fresh container
 * has none of Supabase's — so the restore failed on `public` already existing,
 * then on `supabase_admin` not existing, one role per run.
 *
 * Enumerating them by hand is the wrong fix: there are a dozen Supabase-managed
 * roles, the list changes as Supabase evolves, and each omission costs a full
 * run to discover. This derives the list from the source database, so the
 * rehearsal's prerequisites always match the dump it is restoring.
 *
 * Attributes are deliberately NOT reproduced. The target only needs the names
 * to exist so grants resolve; giving a throwaway container LOGIN roles or
 * BYPASSRLS would be strictly worse. Roles are created NOLOGIN with no
 * password, which is why this output is safe to store beside the dump.
 */
import { ManagementApiExecutor } from '../../src/db/executor.ts'

const token = process.env.SUPABASE_ACCESS_TOKEN
if (token === undefined || token === '') {
  console.error('SUPABASE_ACCESS_TOKEN is not set')
  process.exit(2)
}
const db = new ManagementApiExecutor(
  process.env.SUPABASE_PROJECT_REF ?? 'baujwlzcziasnfhhkchg',
  token,
)

// pg_* roles are predefined by PostgreSQL and already exist in any target;
// creating them would fail.
const { rows } = await db.execute(`
  select rolname from pg_roles
  where rolname not like 'pg\\_%'
  order by rolname
`)

const roles = rows.map((r) => String(r.rolname)).filter((r) => r !== 'postgres')

const lines: string[] = [
  '-- Generated by scripts/backup/emit-roles.ts from the source database.',
  '-- Names only, NOLOGIN, no passwords: the target needs them to exist so the',
  "-- dump's GRANT statements resolve, and nothing more.",
  '',
]

for (const role of roles) {
  lines.push(`do $$ begin`)
  lines.push(`  if not exists (select 1 from pg_roles where rolname = '${role}') then`)
  lines.push(`    create role "${role}" nologin;`)
  lines.push(`  end if;`)
  lines.push(`end $$;`)
}

// Membership the dump's ownership and RLS rely on.
lines.push('')
lines.push('grant "ai_team_app" to postgres;')
lines.push('')

process.stdout.write(`${lines.join('\n')}\n`)
console.error(`emitted ${roles.length} role(s): ${roles.join(', ')}`)

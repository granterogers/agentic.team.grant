#!/usr/bin/env python3
"""
Import a batch of supplied texture images into the Team HQ canvas background library.

    npm run textures:import -- --src <dir> [--batch <name>] [--map <file.json>] [--dry-run]

What it does, per image (png, jpg, webp):
  1. hashes the original bytes. An image whose hash is already in the library is SKIPPED, so a batch can be re-run and an
     earlier import is never overwritten or duplicated;
  2. gives it a stable id (from the map file, else the file name). An id that is already taken by a DIFFERENT image gets a
     numeric suffix, so existing ids and the projects that chose them never change meaning;
  3. writes two optimised WebP files under web/studio/textures/bg/:  <id>.webp  (the tile) and <id>.thumb.webp (192px wide);
  4. adds an entry to library.json and regenerates library.js (the module the page imports; both are committed).

The TILE is built to repeat without a seam on an endless canvas: the image is scaled to 1024px wide and laid out as a 2x2
mirror of itself (2048 wide), so every edge meets its own reflection exactly. A photograph does not need that and is not
imported here; it is the custom-upload path in the page.

The originals are NOT copied into the repository (they are large and stay with whoever supplied them). The library records
the SHA-1 of each original so the source can be identified later.

The map file is optional JSON: { "<file name>": { "id": "...", "name": "...", "category": "...", "credit": "...",
"license": "...", "mode": "tile", "intensity": 0.8, "tint": 0 } }. Without it the id and name come from the file name.

Dependencies: python3 and Pillow, which the other art script (microcement.py) already needs.
"""
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "web" / "studio" / "textures" / "bg"
LIB_JSON = OUT / "library.json"
LIB_JS = OUT / "library.js"
EXTS = {".png", ".jpg", ".jpeg", ".webp"}
HALF_W = 1024
THUMB_W = 192


def slug(text: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return (s or "texture")[:48]


def load_library() -> list:
    if LIB_JSON.exists():
        return json.loads(LIB_JSON.read_text())
    return []


def luminance(rgb) -> float:
    def lin(c):
        c = c / 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4

    r, g, b = rgb
    return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b)


def mirrored_tile(img: Image.Image) -> Image.Image:
    w, h = img.size
    tile = Image.new("RGB", (w * 2, h * 2))
    tile.paste(img, (0, 0))
    tile.paste(img.transpose(Image.FLIP_LEFT_RIGHT), (w, 0))
    tile.paste(img.transpose(Image.FLIP_TOP_BOTTOM), (0, h))
    tile.paste(img.transpose(Image.ROTATE_180), (w, h))
    return tile


def write_js(lib: list) -> None:
    body = json.dumps(lib, indent=2, ensure_ascii=False)
    LIB_JS.write_text(
        "/*\n"
        "  GENERATED by scripts/art/import_textures.py from library.json. Do not edit by hand: import a batch instead.\n"
        "  The canvas background library: one entry per material. Ids are stable (a project stores the id), so an entry\n"
        "  is never renamed or removed; to retire one, set `retired: true`.\n"
        "*/\n"
        f"export const LIBRARY = {body}\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", required=True)
    ap.add_argument("--batch", default="")
    ap.add_argument("--map", default="")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    src = Path(a.src)
    if not src.is_dir():
        print(f"not a directory: {src}", file=sys.stderr)
        return 2
    mapping = {}
    if a.map:
        mapping = json.loads(Path(a.map).read_text())
    OUT.mkdir(parents=True, exist_ok=True)
    lib = load_library()
    seen_hash = {e.get("sourceSha1"): e["id"] for e in lib}
    taken = {e["id"] for e in lib}
    files = sorted(p for p in src.iterdir() if p.suffix.lower() in EXTS)
    if not files:
        print("no images found", file=sys.stderr)
        return 2
    added = 0
    for p in files:
        raw = p.read_bytes()
        sha = hashlib.sha1(raw).hexdigest()
        if sha in seen_hash:
            print(f"skip {p.name}: already imported as '{seen_hash[sha]}'")
            continue
        meta = mapping.get(p.name, {})
        base = slug(meta.get("id") or p.stem)
        tid, n = base, 2
        while tid in taken:
            tid, n = f"{base}-{n}", n + 1
        im = Image.open(p).convert("RGB")
        h = max(1, round(HALF_W * im.height / im.width))
        half = im.resize((HALF_W, h), Image.LANCZOS)
        tile = mirrored_tile(half)
        thumb = half.resize((THUMB_W, max(1, round(THUMB_W * h / HALF_W))), Image.LANCZOS)
        avg = tuple(round(c) for c in half.resize((1, 1), Image.BOX).getpixel((0, 0)))
        lum = luminance(avg)
        entry = {
            "id": tid,
            "name": meta.get("name") or tid.replace("-", " ").title(),
            "category": meta.get("category", "material"),
            "kind": "texture",
            "file": f"/textures/bg/{tid}.webp",
            "thumb": f"/textures/bg/{tid}.thumb.webp",
            "tile": {"w": tile.width, "h": tile.height},
            "mode": meta.get("mode", "tile"),
            "intensity": meta.get("intensity", 1),
            "tint": meta.get("tint", 0),
            "average": "#%02x%02x%02x" % avg,
            "tone": "dark" if lum < 0.18 else "light",
            "batch": a.batch,
            "sourceSha1": sha,
            "credit": meta.get("credit", ""),
            "license": meta.get("license", ""),
        }
        print(f"add  {p.name} -> {tid}  tile {tile.width}x{tile.height}  avg {entry['average']}  tone {entry['tone']}")
        if not a.dry_run:
            tile.save(OUT / f"{tid}.webp", "WEBP", quality=80, method=6)
            thumb.save(OUT / f"{tid}.thumb.webp", "WEBP", quality=80, method=6)
            lib.append(entry)
        taken.add(tid)
        seen_hash[sha] = tid
        added += 1
    if not a.dry_run and added:
        LIB_JSON.write_text(json.dumps(lib, indent=2, ensure_ascii=False) + "\n")
        write_js(lib)
    print(f"{added} added, {len(files) - added} skipped{' (dry run)' if a.dry_run else ''}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

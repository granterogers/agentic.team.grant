/*
 * The studio, served the way Vercel serves it.
 *
 * Every browser check in this repository embeds its own `createServer` that
 * 404s anything which is not a file on disk, and they all navigate to `/` and
 * drive the state in-page. That is fine for the default studio and cannot
 * reach a deep address at all — so a check of a real route would be a check of
 * the harness's own fallback rather than of the product.
 *
 * This is one server that applies the REWRITE IN vercel.json rather than
 * paraphrasing it: any dotless path outside api/, samples/ and
 * fonts/ serves index.html, and everything else is looked up on disk. A check
 * written against this is a check of the addresses Grant will actually open.
 */
import '../../src/safety/arm.ts'
import { readFile } from 'node:fs/promises'
import { createServer, type Server } from 'node:http'
import { extname, join } from 'node:path'

const ROOT = 'web/studio'

const TYPES: Record<string, string> = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8',
  '.woff2': 'font/woff2',
  '.pdf': 'application/pdf',
  '.webp': 'image/webp',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.svg': 'image/svg+xml',
}

/**
 * The rewrite from vercel.json, transcribed once.
 *
 * `/:path((?!api/|samples/|fonts/)[^.]*)` -> `/index.html`. The
 * character class excluding a full stop is what lets a real asset through, and
 * it is also the reason `/basecamp` (no dot) reaches the app while
 * `/bc/bc.css` (a dot) reaches the file.
 */
export const rewrites = (path: string): boolean => {
  const bare = path.replace(/^\//, '')
  // `studio/` was excluded until #382: a /studio/ address is a route to Team HQ now.
  if (/^(api|samples|fonts)\//.test(bare)) return false
  return !bare.includes('.')
}

/*
 * AND THE ONE FILE A DEPLOYMENT WRITES.
 *
 * `web/studio/config.js` names the office this deployment belongs to. It is
 * generated by `npm run config:site` and gitignored, deliberately, so that a
 * clone has no default to be wrong about (ADR-0048) -- which means it is
 * absent on a fresh checkout and present on a machine where somebody has run a
 * deploy. A page served without it resolves its gateway to the empty string
 * and refuses honestly, which is exactly right for a person and wrong for a
 * harness: seventeen suites stub the office by matching `hq-api` in the URL,
 * and a page with no office asks its own origin instead, so the stub never
 * fires and the suite reports that nothing reached the office.
 *
 * Serving one here makes the test server behave like a deployment rather than
 * like a half-configured checkout, and removes a dependency on whether
 * somebody happened to run a deploy on this machine. The address CANNOT be
 * reached: `.invalid` is reserved by RFC 2606 for exactly this, so a suite
 * that forgets to stub something fails loudly rather than quietly talking to a
 * real office. A suite that wants a different one sets `window.HQ_API` in an
 * init script, which runs first and wins -- config.js does not clobber a value
 * that is already set.
 *
 * The file on disk wins when there is one, so a machine mid-deploy is
 * unchanged.
 */
const FALLBACK_CONFIG = [
  '/* Served by scripts/verify/serve-studio.ts because there is no',
  '   web/studio/config.js on disk. An address that cannot be reached, so a',
  '   suite that forgets to stub the office fails loudly. See ADR-0048. */',
  "window.HQ_API = window.HQ_API || 'https://office.invalid/functions/v1/hq-api'",
  '',
].join('\n')

export const serveStudio = async (port: number): Promise<Server> => {
  const server = createServer(async (req, res) => {
    const path = (req.url ?? '/').split('?')[0] ?? '/'
    const wanted = path === '/' || rewrites(path) ? 'index.html' : path.replace(/^\//, '')
    const file = join(ROOT, wanted)
    if (wanted === 'config.js') {
      try {
        const onDisk = await readFile(file)
        res.writeHead(200, { 'content-type': TYPES['.js'] ?? 'text/javascript' })
        res.end(onDisk)
      } catch {
        res.writeHead(200, { 'content-type': TYPES['.js'] ?? 'text/javascript' })
        res.end(FALLBACK_CONFIG)
      }
      return
    }
    try {
      const body = await readFile(file)
      res.writeHead(200, { 'content-type': TYPES[extname(file)] ?? 'application/octet-stream' })
      res.end(body)
    } catch {
      res.writeHead(404, { 'content-type': 'text/plain' })
      res.end('not found')
    }
  })
  await new Promise<void>((r) => {
    server.listen(port, '127.0.0.1', () => {
      r()
    })
  })
  return server
}

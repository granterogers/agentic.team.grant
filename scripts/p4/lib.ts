/**
 * Shared pieces of the P4 second-user acceptance: a REAL session for each person, and the gateway as a signed-in browser
 * calls it. Nothing here prints a credential.
 *
 * The second person signs in by the password grant against Supabase Auth (the login was created by
 * scripts/p4/provision-second-person.ts and its password lives in the Vault). Grant's session is minted the way
 * `verify:basecamp-signin` does it, by the office producing a link for him is NOT available to the machine key (it mints a
 * test member only), so Grant-side checks use the real office through a magic link generated by the admin API and consumed
 * without any mail.
 */
import { ManagementApiExecutor } from '../../src/db/executor.ts'
import { apiKeys, SECOND_EMAIL } from './identity.ts'

export const REF = process.env.SUPABASE_PROJECT_REF ?? 'baujwlzcziasnfhhkchg'
export const db = new ManagementApiExecutor(REF, process.env.SUPABASE_ACCESS_TOKEN ?? '')
export const ENDPOINT = `https://${REF}.supabase.co/functions/v1/hq-api`

export type Session = { access_token: string; refresh_token: string; expires_at: number }

export const vaultSecret = async (name: string): Promise<string> =>
  String(
    (
      await db.execute(
        `select decrypted_secret as v from vault.decrypted_secrets where name = '${name}'`,
      )
    ).rows[0]?.v ?? '',
  )

/** A real Supabase session for the second person: the password grant, exactly as a login form would. */
export const secondSession = async (): Promise<Session> => {
  const { anon } = await apiKeys()
  const password = await vaultSecret('p4.second_person.password')
  if (password === '') throw new Error('the second person has no stored password')
  // The provider's auth edge sometimes answers "upstream request timeout" (plain text): that is the platform, not a
  // result. Retry with a pause, and say so, rather than letting an infra failure enter a measurement as data.
  let last = ''
  for (let attempt = 1; attempt <= 5; attempt += 1) {
    const r = await fetch(`https://${REF}.supabase.co/auth/v1/token?grant_type=password`, {
      method: 'POST',
      headers: { apikey: anon, 'content-type': 'application/json' },
      body: JSON.stringify({ email: SECOND_EMAIL, password }),
    })
    const text = await r.text()
    try {
      const b = JSON.parse(text) as Partial<Session> & { msg?: string; error_description?: string }
      if (r.ok && b.access_token !== undefined) return b as Session
      last = String(b.msg ?? b.error_description)
    } catch {
      last = text.slice(0, 60)
    }
    console.log(`  (auth edge said "${last}" - attempt ${attempt} of 5, waiting)`)
    await new Promise((ok) => setTimeout(ok, 8000))
  }
  throw new Error(`no session for the second person: ${last}`)
}

/** Grant's email, read from the office - never typed here. */
export const grantEmail = async (): Promise<string> =>
  String(
    (
      await db.execute(
        `select m.email from public.office_members m where m.kind = 'person' and m.owner_key = 'grant' limit 1`,
      )
    ).rows[0]?.email ?? '',
  )

/**
 * A real session for Grant, with no mail sent: the admin API produces the magic link, the verify URL is followed WITHOUT
 * redirects, and the tokens are read from the Location fragment. Session only lives in memory.
 */
export const grantSession = async (): Promise<Session> => {
  // Same platform behaviour as the second person's login: a plain-text edge timeout is not an answer.
  let last = ''
  for (let attempt = 1; attempt <= 5; attempt += 1) {
    try {
      return await grantSessionOnce()
    } catch (e) {
      last = e instanceof Error ? e.message.slice(0, 80) : String(e)
      console.log(`  (Grant's session: "${last}" - attempt ${attempt} of 5, waiting)`)
      await new Promise((ok) => setTimeout(ok, 8000))
    }
  }
  throw new Error(`no session for Grant: ${last}`)
}

const grantSessionOnce = async (): Promise<Session> => {
  const { anon, service } = await apiKeys()
  const email = await grantEmail()
  if (email === '') throw new Error('Grant has no person email on the office')
  const gen = await fetch(`https://${REF}.supabase.co/auth/v1/admin/generate_link`, {
    method: 'POST',
    headers: {
      apikey: service,
      Authorization: `Bearer ${service}`,
      'content-type': 'application/json',
    },
    body: JSON.stringify({ type: 'magiclink', email }),
  })
  const g = (await gen.json()) as { action_link?: string; hashed_token?: string }
  if (g.hashed_token === undefined) throw new Error('no link generated for Grant')
  const v = await fetch(`https://${REF}.supabase.co/auth/v1/verify`, {
    method: 'POST',
    headers: { apikey: anon, 'content-type': 'application/json' },
    body: JSON.stringify({ type: 'magiclink', token_hash: g.hashed_token }),
  })
  const b = (await v.json()) as Partial<Session>
  if (b.access_token === undefined) throw new Error('Grant link did not yield a session')
  return b as Session
}

export type Reply = { status: number; json: unknown; text: string }

const parse = async (r: Response): Promise<Reply> => {
  const text = await r.text()
  let json: unknown = null
  try {
    json = JSON.parse(text)
  } catch {
    /* not JSON */
  }
  return { status: r.status, json, text }
}

/** A section read as a signed-in browser does it. */
export const read = async (token: string, section: string, extra = ''): Promise<Reply> =>
  parse(
    await fetch(`${ENDPOINT}?section=${section}${extra}`, {
      headers: { Authorization: `Bearer ${token}` },
    }),
  )

/** An action as a signed-in browser does it. */
export const act = async (
  token: string,
  action: string,
  args: Record<string, unknown> = {},
): Promise<Reply> =>
  parse(
    await fetch(ENDPOINT, {
      method: 'POST',
      headers: { Authorization: `Bearer ${token}`, 'content-type': 'application/json' },
      body: JSON.stringify({ action, args }),
    }),
  )


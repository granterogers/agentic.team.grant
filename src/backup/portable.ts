/**
 * A copy of everything, taken on a schedule and kept somewhere.
 *
 * §16: *"A backup feature is incomplete until restoration is tested."* This
 * system had the first half twice over — a nightly `pg_dump` in GitHub Actions,
 * and `scripts/backup/export-portable.ts` for a human to hold — and then
 * Actions were switched off and the nightly dump went with them. Since
 * 2026-09-08 nothing has taken a backup at all.
 *
 * ## Why it is not a pg_dump
 *
 * Because there is nowhere left to run one. `pg_dump` is a binary; the only
 * compute is a Deno Edge Function. The notebook reader got out of the same
 * corner by measuring the dependency and finding it did not need a browser
 * (0138), and the same question asked here has a different answer: a dump
 * genuinely needs the binary and the Postgres wire protocol, and this system
 * has neither.
 *
 * What it has is the Management API, which is how every other row in this
 * codebase is read. So the backup is what `export-portable.ts` already
 * produced — every table, the schema that describes it, and the migration list
 * needed to rebuild it — as one gzipped JSON object.
 *
 * That is a weaker artifact than a dump and the weakness is worth naming:
 * restoring means applying the migrations from git and then loading rows,
 * rather than one `psql` command. The migrations are in git and the loading is
 * rehearsed, which is what makes it tractable rather than theoretical.
 *
 * ## Why the code moved here from the script
 *
 * The script writes to the local filesystem with `node:fs` and gzips with
 * `node:zlib`. Neither is available to the worker that now has to run this, so
 * the logic is here in Web APIs — `CompressionStream`, `crypto.subtle` — which
 * Deno and Node both have, and the script becomes a caller like any other.
 *
 * ## What is deliberately not in it
 *
 * Credentials. `vault` is excluded, exactly as the nightly dump excluded it: a
 * portable file full of decryptable secrets is a worse problem than the one it
 * solves. What would need re-entering is listed inside the file instead, so the
 * person restoring is told rather than left to discover it.
 */

import type { SqlExecutor } from '../db/executor.ts'

export interface Archive {
  readonly name: string
  readonly bytes: Uint8Array
  readonly sha256: string
  readonly rows: number
  readonly tables: number
  readonly rawBytes: number
  readonly latestMigration: string
}

/** What a restore would have to put back by hand. Inside the file, not beside it. */
const CREDENTIALS_NOT_INCLUDED = [
  'slack.signing_secret, slack.config_token, slack.config_refresh_token — api.slack.com',
  'telegram.webhook_secret — regenerate, then npm run deploy:telegram',
  'telegram bot tokens — BotFather, then npm run telegram:webhooks',
  'hq.api_token — npm run deploy:hq',
  'notebook.storage_state — npm run notebook:bootstrap, signs in by hand',
  'notebook.reader_secret — regenerated by npm run deploy:hq',
  'google.* — the OAuth consent flow on the Connections page',
  'openrouter.api_key, groq.api_key, openai — the provider dashboards',
  'supabase.db_password — reset on the project',
]

const gzip = async (text: string): Promise<Uint8Array> => {
  // `CompressionStream` rather than `node:zlib`: this runs in the worker, and
  // the worker is Deno. Both runtimes have it; only one has zlib.
  const stream = new Blob([text]).stream().pipeThrough(new CompressionStream('gzip'))
  return new Uint8Array(await new Response(stream).arrayBuffer())
}

const sha256 = async (bytes: Uint8Array): Promise<string> => {
  const digest = await crypto.subtle.digest('SHA-256', bytes as unknown as ArrayBuffer)
  return [...new Uint8Array(digest)].map((b) => b.toString(16).padStart(2, '0')).join('')
}

/**
 * Read everything and gzip it.
 *
 * Whole tables, no WHERE clause anywhere. This is a backup: a filter here is a
 * row somebody does not get back.
 */
/**
 * Every table a backup must contain.
 *
 * Exported, and separate from `buildArchive`, so the rehearsal can ask "would
 * tonight's backup cover everything?" without building one.
 *
 * That distinction turned out to matter. The rehearsal used to answer the
 * coverage question by comparing the STORED archive's table list against the
 * live schema — which fails, correctly and uselessly, every time a migration
 * adds a table between the last nightly run and the check. `project_aliases`
 * (0153) tripped it that way: the builder was fine, the archive was simply
 * older than the table. A check that cannot tell "the backup skips this" from
 * "the backup predates this" is reporting the wrong defect, and the one it
 * hides is the serious one.
 */
export async function tablesToBackUp(
  db: SqlExecutor,
): Promise<{ table_schema: string; table_name: string }[]> {
  return (
    await db.execute(`
      select table_schema, table_name
        from information_schema.tables
       where table_schema in ('public', 'app')
         and table_type = 'BASE TABLE'
       order by table_schema, table_name
    `)
  ).rows as { table_schema: string; table_name: string }[]
}

export async function buildArchive(db: SqlExecutor, projectRef: string): Promise<Archive> {
  const tables = await tablesToBackUp(db)

  const data: Record<string, unknown[]> = {}
  let rows = 0
  for (const t of tables) {
    const result = await db.execute(`select * from "${t.table_schema}"."${t.table_name}"`)
    data[`${t.table_schema}.${t.table_name}`] = [...result.rows]
    rows += result.rows.length
  }

  // The schema, so the file is self-describing rather than only meaningful to
  // someone holding this repository at the right commit.
  const schema = (
    await db.execute(`
      select table_schema || '.' || table_name as t, column_name, data_type, is_nullable
        from information_schema.columns
       where table_schema in ('public', 'app')
       order by table_schema, table_name, ordinal_position
    `)
  ).rows

  const migrations = (
    await db.execute('select name from app.schema_migrations order by name')
  ).rows.map((r) => String(r.name))
  const latestMigration = migrations[migrations.length - 1] ?? 'none'

  const json = JSON.stringify({
    exported_at: new Date().toISOString(),
    project_ref: projectRef,
    note:
      'Portable JSON export. NOT a pg_dump — restoring means applying the ' +
      'migrations from git, then loading these rows. Contains no credentials: ' +
      'the vault schema is deliberately excluded.',
    credentials_not_included: CREDENTIALS_NOT_INCLUDED,
    latest_migration: latestMigration,
    migrations,
    row_counts: Object.fromEntries(Object.entries(data).map(([k, v]) => [k, v.length])),
    schema,
    data,
  })

  const bytes = await gzip(json)
  // Sortable by name, because Storage lists lexicographically and "the newest
  // one" should not need a date parser to work out.
  const stamp = new Date().toISOString().replace(/[:-]|\.\d{3}/g, '')
  return {
    name: `aiteamhq-${stamp}.json.gz`,
    bytes,
    sha256: await sha256(bytes),
    rows,
    tables: tables.length,
    rawBytes: json.length,
    latestMigration,
  }
}

export const BUCKET = 'backups'

interface StorageObject {
  readonly name: string
  readonly created_at?: string
}

/**
 * Make sure the bucket exists, and that it is private.
 *
 * Private is the whole point and is asserted rather than assumed: the avatars
 * bucket next to it is public, one wrong flag would publish every row in the
 * database at a guessable URL, and "I created it private in a script once" is
 * not a control.
 */
export async function ensureBucket(ref: string, serviceKey: string): Promise<string> {
  const base = `https://${ref}.supabase.co/storage/v1`
  const headers = { Authorization: `Bearer ${serviceKey}`, 'Content-Type': 'application/json' }

  const existing = await fetch(`${base}/bucket/${BUCKET}`, { headers })
  if (existing.ok) {
    const bucket = (await existing.json()) as { public?: boolean }
    if (bucket.public === true) {
      throw new Error(
        `the ${BUCKET} bucket is PUBLIC. Every row in the database would be readable ` +
          'at a guessable URL. Refusing to upload until it is private.',
      )
    }
    return 'already private'
  }

  const created = await fetch(`${base}/bucket`, {
    method: 'POST',
    headers,
    body: JSON.stringify({ id: BUCKET, name: BUCKET, public: false }),
  })
  if (!created.ok) {
    throw new Error(`could not create the ${BUCKET} bucket: http ${String(created.status)}`)
  }
  return 'created, private'
}

/** Put the archive in the bucket, and its checksum beside it. */
export async function uploadArchive(
  ref: string,
  serviceKey: string,
  archive: Archive,
): Promise<string> {
  const base = `https://${ref}.supabase.co/storage/v1/object/${BUCKET}`
  const put = async (path: string, body: Uint8Array | string, type: string): Promise<void> => {
    const response = await fetch(`${base}/${path}`, {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${serviceKey}`,
        'Content-Type': type,
        'x-upsert': 'true',
      },
      // `Uint8Array<ArrayBuffer>` rather than a bare Uint8Array: the DOM
      // typings narrowed BodyInit and a generic buffer no longer satisfies it.
      body: typeof body === 'string' ? body : (body as Uint8Array<ArrayBuffer>),
    })
    if (!response.ok) {
      throw new Error(
        `upload of ${path} failed: http ${String(response.status)} ` +
          `${(await response.text()).slice(0, 160)}`,
      )
    }
  }

  await put(archive.name, archive.bytes, 'application/gzip')
  // Beside the file rather than only in the log: a corrupted copy should be
  // detectable by whoever finds the file, not only by whoever took it.
  await put(`${archive.name}.sha256`, `${archive.sha256}  ${archive.name}\n`, 'text/plain')
  return archive.name
}

/** What is in the bucket, newest first. */
export async function listArchives(
  ref: string,
  serviceKey: string,
): Promise<readonly StorageObject[]> {
  const response = await fetch(`https://${ref}.supabase.co/storage/v1/object/list/${BUCKET}`, {
    method: 'POST',
    headers: { Authorization: `Bearer ${serviceKey}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ prefix: '', limit: 200, sortBy: { column: 'name', order: 'desc' } }),
  })
  if (!response.ok) return []
  const all = (await response.json()) as StorageObject[]
  return all.filter((o) => o.name.endsWith('.json.gz'))
}

/**
 * Fetch one back out.
 *
 * Used by the restore rehearsal, which is the half of §16 that makes the other
 * half mean anything.
 */
export async function downloadArchive(
  ref: string,
  serviceKey: string,
  name: string,
): Promise<Uint8Array> {
  const response = await fetch(`https://${ref}.supabase.co/storage/v1/object/${BUCKET}/${name}`, {
    headers: { Authorization: `Bearer ${serviceKey}` },
  })
  if (!response.ok) {
    throw new Error(`could not download ${name}: http ${String(response.status)}`)
  }
  return new Uint8Array(await response.arrayBuffer())
}

/** Ungzip an archive back into the object it was made from. */
export async function readArchive(bytes: Uint8Array): Promise<Record<string, unknown>> {
  const stream = new Blob([bytes as Uint8Array<ArrayBuffer>])
    .stream()
    .pipeThrough(new DecompressionStream('gzip'))
  return JSON.parse(await new Response(stream).text()) as Record<string, unknown>
}

/** The checksum of some bytes, so a caller can compare without importing crypto. */
export const checksum = sha256

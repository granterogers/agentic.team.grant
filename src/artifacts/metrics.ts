/**
 * A sensible width for something not in the table.
 *
 * The alternative is 0, which makes an unknown character free and lets a line
 * of them run off the page — the silent version of the defect this module
 * exists to stop. A lower-case n is a fair average and errs towards breaking
 * a line early, which is the cheap direction.
 */
export const FALLBACK_WIDTH = 500

/** How wide a string is, in points, set in `face` at `size`. */
export function widthOf(text: string, face: Face, size: number): number {
  const table = WIDTHS[face]
  let mille = 0
  for (const ch of text) {
    const cp = ch.codePointAt(0) ?? 32
    mille += table[cp] ?? FALLBACK_WIDTH
  }
  return (mille * size) / 1000
}

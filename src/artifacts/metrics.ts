/**
 * The advance widths of the fourteen fonts every PDF reader already has.
 *
 * A PDF that names Helvetica embeds nothing — the reader supplies the face —
 * which is why an office running in Deno with no dependencies can still
 * produce a typographically correct document. The catch is that NOTHING in
 * the file says how wide a character is, so the writer has to know, and a
 * writer that guesses produces the one defect #258 forbids by name: clipped
 * content and overflowing lines.
 *
 * ## Where these numbers came from
 *
 * Parsed out of the `hmtx` and `cmap` tables of the Liberation faces shipped
 * with this machine (`/usr/share/fonts/truetype/liberation/`), scaled to the
 * 1/1000 em PDF uses. Liberation Sans is metric-compatible with Arial and
 * Arial is metric-compatible with Helvetica; Liberation Serif is
 * metric-compatible with Times New Roman.
 *
 * They were checked against the values everybody knows before being trusted:
 * Helvetica space 278, A 667, i 222, W 944, m 833; Times A 722, i 278. All
 * six match, which is the control — a table extracted from a substituted font
 * would not.
 *
 * Regenerate with `npm run fontmetrics` if a face is ever added. Do not edit
 * a number by hand: a single wrong width is a line that overflows in one
 * paragraph of one report, which is exactly the failure nobody finds by
 * reading.
 */


/**
 * Corpus discipline — §13.
 *
 * Three corpora, and the difference between them is not their contents but
 * WHEN they were fixed relative to a fix.
 *
 *   1. DEVELOPMENT   - visible, tuned against, used while building.
 *   2. FROZEN HELD-OUT - fixed before any production fix, and not looked at.
 *   3. FRESH SEEDED  - generated new on every serious run.
 *
 * ## Freezing a generator is not freezing a list
 *
 * The obvious way to freeze a corpus is to write the sentences down. That is
 * wrong here and the reason is the whole design: these scenarios are
 * COMPOSED from families, personas and a seed, so the sentences are a
 * function of the code. Writing them down would freeze the output and leave
 * the function free to change underneath — and then a run six weeks from now
 * would compare today's numbers against a corpus generated by a different
 * instrument while appearing to compare like with like.
 *
 * So what is frozen is the seed AND a fingerprint of what the generator
 * produces from it. If the fingerprint moves, the corpus moved, and the two
 * runs are not comparable. That is exactly what `JUDGE_VERSION` does for the
 * judge's wording, and CLAUDE.md's argument for it applies unchanged: two
 * runs on different versions are two different instruments.
 *
 * The fingerprint going red is not a failure. It is a notice that a
 * comparison is no longer valid, and the honest response is to record a new
 * baseline rather than to reach for the old number.
 */

import { createHash } from 'node:crypto'
import { generateCorpus } from './compose.ts'
import { PERSONAS } from './persona.ts'
import type { World } from './world.ts'
import { DEFAULT_WORLD } from './world.ts'

/**
 * The seed used while building the harness. Every finding in the 21
 * September baseline came from this one, so it is tuned against by
 * definition and must never be the only thing a fix is tested on.
 */
export const DEVELOPMENT_SEED = 1

/**
 * The held-out seed.
 *
 * Chosen before any production fix was made, and **the scenarios it
 * generates have deliberately not been read**. §13: expectation edits only
 * for demonstrated harness defects, with an audit note.
 *
 * The number itself is arbitrary and that is the point — it was not selected
 * by trying several and keeping an interesting one, which would make it
 * development material wearing a held-out label.
 */
export const HELD_OUT_SEED = 20260921

/**
 * What the generator produced from the held-out seed at freeze time.
 *
 * Recomputed by `npm run shadow:freeze --check` and compared. A change here
 * means the generator changed, which means any comparison across it is
 * invalid.
 */
export const FROZEN = {
  at: '2026-09-21',
  /** The commit the freeze was taken against. An intention is not a freeze. */
  against: 'the branch head at the time of the first baseline',
  seed: HELD_OUT_SEED,
  perFamily: 2,
  personas: PERSONAS.map((p) => `${p.slug}@${p.version}`),
} as const

/**
 * A fingerprint of a generated corpus.
 *
 * Over the SENT SENTENCES and the recorded intents together, because either
 * alone misses half of what could drift: the same sentence with a different
 * recorded expectation is a different test, and CLAUDE.md records a harness
 * expectation being wrong about half the time on a first pass.
 */
export const fingerprint = (world: World, seed: number, perFamily = 2): string => {
  const corpus = generateCorpus(world, seed, perFamily)
  const h = createHash('sha256')
  for (const s of corpus) {
    h.update(s.id)
    for (const t of s.turns) {
      h.update('\u0000')
      h.update(t.say)
      h.update('\u0000')
      h.update(t.intent.want)
      h.update('\u0000')
      h.update(t.intent.effect)
      h.update('\u0000')
      h.update((t.intent.withdrawn ?? []).join('|'))
      h.update('\u0000')
      h.update((t.intent.forbids ?? []).join('|'))
    }
  }
  return h.digest('hex').slice(0, 16)
}

/** The held-out corpus, generated fresh each time from the frozen seed. */
export const heldOut = (world: World = DEFAULT_WORLD) =>
  generateCorpus(world, HELD_OUT_SEED, FROZEN.perFamily)

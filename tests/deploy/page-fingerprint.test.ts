describe('every input changes the fingerprint (mutation per input class)', () => {
  let base = ''
  beforeAll(async () => {
    base = await fingerprintOf()
  })

  // Every edit keeps the file the SAME LENGTH, so only the content digest can tell the two apart. A mutation that also
  // changed the size would be caught by the size field and prove nothing about the digest.
  const fileMutations: [string, string, string | Buffer][] = [
    ['a studio file shared at the root', 'web/studio/app.js', 'export const a = 2\n'],
    ['a nested studio file', 'web/studio/bc/compose.js', 'export const c = 2\n'],
    ['the page entry', 'web/studio/index.html', '<html>Team HX</html>'],
    ['a binary asset, one byte', 'web/studio/fonts/f.woff2', Buffer.from([0, 1, 2, 3, 250, 252])],
    [
      'the generated config.js (another office address, same length)',
      'web/studio/config.js',
      "window.HQ_API = window.HQ_API || 'https://bbbb/hq-api'\n",
    ],
    ['the reader function', 'api/notebook.py', 'print("readeR")\n'],
    ['the writer function', 'api/notebook-act.py', 'print("writeR")\n'],
    ['the script the writer spawns', 'scripts/notebook/act.py', 'print("acT")\n'],
    ['the dependency list', 'requirements.txt', 'notebooklm-pz\n'],
    ['the function configuration', 'vercel.json', '{"functionz":{}}\n'],
  ]
  it.each(fileMutations)('%s keeps its length', (_label, rel, body) => {
    expect(Buffer.byteLength(body)).toBe(readFileSync(join(root, rel)).length)
  })
  it.each(fileMutations)('%s', async (_label, rel, body) => {
    const original = readFileSync(join(root, rel))
    put(rel, body)
    try {
      expect(await fingerprintOf()).not.toBe(base)
    } finally {
      put(rel, original)
    }
  })

  it('a studio file added', async () => {
    put('web/studio/new.js', 'x')
    try {
      expect(await fingerprintOf()).not.toBe(base)
    } finally {
      rmSync(join(root, 'web/studio/new.js'))
    }
  })

  it('the generated config.js absent, as when config:site was not run before fingerprinting', async () => {
    const original = readFileSync(join(root, 'web/studio/config.js'))
    rmSync(join(root, 'web/studio/config.js'))
    try {
      expect(await fingerprintOf()).not.toBe(base)
    } finally {
      put('web/studio/config.js', original)
    }
  })

  it('config.js is still generated by config:site and ignored by git, so it is an input the repository cannot show', () => {
    expect(read('scripts/config-site.ts')).toContain("'web/studio/config.js'")
    expect(read('.gitignore')).toMatch(/^web\/studio\/config\.js$/m)
  })

  it('a studio file removed', async () => {
    const original = readFileSync(join(root, 'web/studio/studio.css'))
    rmSync(join(root, 'web/studio/studio.css'))
    try {
      expect(await fingerprintOf()).not.toBe(base)
    } finally {
      put('web/studio/studio.css', original)
    }
  })

  it('a studio file renamed with the same content', async () => {
    const original = readFileSync(join(root, 'web/studio/studio.css'))
    rmSync(join(root, 'web/studio/studio.css'))
    put('web/studio/studio2.css', original)
    try {
      expect(await fingerprintOf()).not.toBe(base)
    } finally {
      rmSync(join(root, 'web/studio/studio2.css'))
      put('web/studio/studio.css', original)
    }
  })

  const nonFile: [string, (i: MutableInputs) => void][] = [
    [
      'deployment name',
      (i) => {
        i.deployment.name = 'other'
      },
    ],
    [
      'deployment target',
      (i) => {
        i.deployment.target = 'preview'
      },
    ],
    [
      'deployment projectSettings',
      (i) => {
        i.deployment.projectSettings = { framework: 'nextjs' }
      },
    ],
    [
      'a build-affecting project setting',
      (i) => {
        i.project.settings.nodeVersion = '22.x'
      },
    ],
    [
      'the function region setting',
      (i) => {
        i.project.settings.serverlessFunctionRegion = 'sfo1'
      },
    ],
    [
      'an environment variable added',
      (i) => {
        i.project.envNames.push('NEW_VAR')
      },
    ],
    [
      'an environment variable removed',
      (i) => {
        i.project.envNames.length = 0
      },
    ],
    [
      'a variable the script does not supply edited by hand (its update time moves, its name does not)',
      (i) => {
        i.project.envStamps.OTHER_FLAG = 1_760_000_000_001
      },
    ],
    [
      'a supplied variable that stops being supplied (null stamp replaced by a time)',
      (i) => {
        i.project.envStamps.NOTEBOOK_READER_SECRET = 1_760_000_000_000
      },
    ],
    [
      'the reader secret rotated',
      (i) => {
        i.envDigests.NOTEBOOK_READER_SECRET = envDigest('secret-two')
      },
    ],
    [
      'a new supplied environment digest',
      (i) => {
        i.envDigests.OTHER = envDigest('x')
      },
    ],
  ]
  it.each(nonFile)('%s', async (_label, mutate) => {
    expect(await fingerprintOf(mutate)).not.toBe(base)
  })

  it('the algorithm version is an input: identical inputs under another version differ', async () => {
    const i = await baseInputs()
    expect(pageFingerprint(i, FINGERPRINT_SCHEMA + 1)).not.toBe(pageFingerprint(i))
    expect(pageFingerprint(i, FINGERPRINT_SCHEMA)).toBe(pageFingerprint(i))
  })
})

describe('the mutation tests can fail (controls: a fingerprint that ignores one input class misses that mutation)', () => {
  const blind =
    (drop: (i: MutableInputs) => void) => async (mutate: (i: MutableInputs) => void) => {
      const a = await baseInputs()
      drop(a)
      const b = await baseInputs()
      mutate(b)
      drop(b)
      return pageFingerprint(a) === pageFingerprint(b)
    }
  it('content digests ignored: a same-length content change goes unseen', async () => {
    const dropShas = blind((i) => {
      for (const f of i.files) f.sha = ''
    })
    expect(
      await dropShas((i) => {
        const f = i.files.find((x) => x.file === 'app.js')
        if (f !== undefined) f.sha = 'changed'
      }),
    ).toBe(true)
  })
  it('secret digests ignored: a rotation goes unseen', async () => {
    const dropDigests = blind((i) => {
      i.envDigests = {}
    })
    expect(
      await dropDigests((i) => {
        i.envDigests.NOTEBOOK_READER_SECRET = envDigest('secret-two')
      }),
    ).toBe(true)
  })
  it('update times ignored: a hand edit of a variable goes unseen', async () => {
    const dropStamps = blind((i) => {
      i.project.envStamps = {}
    })
    expect(
      await dropStamps((i) => {
        i.project.envStamps.OTHER_FLAG = 1
      }),
    ).toBe(true)
  })
  it('project settings ignored: a region change goes unseen', async () => {
    const dropSettings = blind((i) => {
      i.project.settings = {}
    })
    expect(
      await dropSettings((i) => {
        i.project.settings.serverlessFunctionRegion = 'sfo1'
      }),
    ).toBe(true)
  })
})

describe('changes that must NOT matter', () => {
  it('file modification times', async () => {
    const before = await fingerprintOf()
    const t = new Date(2020, 0, 1)
    utimesSync(join(root, 'web/studio/app.js'), t, t)
    expect(await fingerprintOf()).toBe(before)
  })

  it('a file under raw/, which is never uploaded', async () => {
    const before = await fingerprintOf()
    put('web/studio/textures/raw/another.png', Buffer.from('more source photographs'))
    try {
      expect(await fingerprintOf()).toBe(before)
    } finally {
      rmSync(join(root, 'web/studio/textures/raw/another.png'))
    }
  })

  it('rewriting a file with identical bytes', async () => {
    const before = await fingerprintOf()
    put('web/studio/app.js', readFileSync(join(root, 'web/studio/app.js')))
    expect(await fingerprintOf()).toBe(before)
  })

  it('the order inputs are listed in', async () => {
    const i = await baseInputs()
    const shuffled: PageInputs = {
      ...i,
      files: [...i.files].reverse(),
      project: { ...i.project, envNames: [...i.project.envNames].reverse() },
    }
    expect(pageFingerprint(shuffled)).toBe(pageFingerprint(i))
  })

  it('the value of a secret is never in the fingerprint inputs, only a digest', () => {
    expect(envDigest('secret-one')).not.toContain('secret-one')
    expect(envDigest('secret-one')).toHaveLength(64)
    expect(envDigest('secret-one')).not.toBe(envDigest('secret-two'))
  })
})

describe('the skip decision fails toward deploying', () => {
  const fp = 'a'.repeat(64)
  it('skips only when READY and the recorded fingerprint is identical', () => {
    expect(decideSkip({ state: 'READY', meta: { [FINGERPRINT_META_KEY]: fp } }, fp).skip).toBe(true)
  })
  it.each([
    ['no live deployment', null],
    [
      'a live deployment that is not READY',
      { state: 'ERROR', meta: { [FINGERPRINT_META_KEY]: fp } },
    ],
    ['no recorded fingerprint (an older deployment)', { state: 'READY', meta: {} }],
    ['no meta at all', { state: 'READY' }],
    ['an empty recorded fingerprint', { state: 'READY', meta: { [FINGERPRINT_META_KEY]: '' } }],
    [
      'a different recorded fingerprint',
      { state: 'READY', meta: { [FINGERPRINT_META_KEY]: 'b'.repeat(64) } },
    ],
  ])('deploys on %s', (_label, live) => {
    expect(decideSkip(live as Parameters<typeof decideSkip>[0], fp).skip).toBe(false)
  })
  it('deploys when forced, even if every input matches', () => {
    expect(
      decideSkip({ state: 'READY', meta: { [FINGERPRINT_META_KEY]: fp } }, fp, true).skip,
    ).toBe(false)
  })
})


/** The inputs, in a mutable shape so a test can change one field at a time. */
type MutableInputs = {
  files: { file: string; sha: string; size: number }[]
  deployment: { name: string; target: string; projectSettings: unknown }
  project: {
    settings: Record<string, unknown>
    envNames: string[]
    envStamps: Record<string, number | null>
  }
  envDigests: Record<string, string>
}
const baseInputs = async (): Promise<MutableInputs> => ({
  files: toUploadList(await collectPageFiles(root)),
  deployment: { name: 'ai-team-hq', target: 'production', projectSettings: { framework: null } },
  project: {
    settings: pickProjectSettings({
      framework: null,
      nodeVersion: '24.x',
      serverlessFunctionRegion: 'iad1',
    }),
    envNames: ['NOTEBOOK_READER_SECRET', 'OTHER_FLAG'],
    envStamps: { NOTEBOOK_READER_SECRET: null, OTHER_FLAG: 1_760_000_000_000 },
  },
  envDigests: { NOTEBOOK_READER_SECRET: envDigest('secret-one') },
})
const fingerprintOf = async (mutate?: (i: MutableInputs) => void): Promise<string> => {
  const i = await baseInputs()
  mutate?.(i)
  return pageFingerprint(i)
}


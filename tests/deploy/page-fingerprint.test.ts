/**
 * Skipping a redeploy is only safe if the comparison covers every input. This proves coverage three ways:
 *   1. a mutation of every input class changes the fingerprint, and the changes that must NOT matter do not;
 *   2. the file set the fingerprint reads is the one the two deploy scripts upload (their own lists are parsed, and the
 *      parser is shown to fail on a script with a line removed);
 *   3. every key the deploy scripts send to Vercel is one the fingerprint knows (a new key fails until somebody decides).
 */
